import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const prod = process.argv[2] === "production";

/** Obsidian loads the plugin from vault/plugin-scripts copies, not this source folder. */
const INSTALL_DIRS = [
	path.resolve(
		"C:/Users/lihua/Desktop/obsidian weave插件系列开发/plugin testing library/.obsidian/plugins/todo",
	),
	path.resolve(
		"C:/Users/lihua/AppData/Roaming/obsidian/plugin-scripts/719376ae73e7efb6/.obsidian/plugins/todo",
	),
];

const ARTIFACTS = ["main.js", "manifest.json", "styles.css"];

function deployArtifacts() {
	for (const outDir of INSTALL_DIRS) {
		if (!fs.existsSync(path.dirname(outDir))) continue;
		fs.mkdirSync(outDir, { recursive: true });
		for (const name of ARTIFACTS) {
			const src = path.join(__dirname, name);
			if (!fs.existsSync(src)) continue;
			fs.copyFileSync(src, path.join(outDir, name));
		}
		console.log(`[deploy] → ${outDir}`);
	}
}

const deployPlugin = {
	name: "deploy-todo-plugin",
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length > 0) return;
			deployArtifacts();
		});
	},
};

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
	],
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	plugins: [deployPlugin],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	console.log("[dev] watching; artifacts sync to Obsidian install dirs on rebuild");
	await context.watch();
}
